// npm run mutate -> runs the eval suite on the baseline, then on every mutant; writes report.md.
import { writeFileSync } from 'node:fs';
import { BASELINE } from './sut';
import { CASES, runSuite } from './suite';
import { MUTATORS } from './mutators';
import { gate, pct, summarize, THRESHOLDS, type MutantResult } from './score';

const out: string[] = ['# Mutation report', '', '_Generated by `npm run mutate`. System under test is a deterministic simulation (no real LLM)._', ''];
const finish = (code: number) => {
  writeFileSync('report.md', out.join('\n') + '\n');
  console.log(out.join('\n'));
  process.exit(code);
};

const base = runSuite(BASELINE);
const baseFailed = base.filter((c) => c.failed.length);
if (baseFailed.length) {
  out.push('## INVALID BASELINE', '', 'The unmutated system fails the suite, so kills would be meaningless. Aborting.', '');
  for (const c of baseFailed) out.push(`- \`${c.id}\`: ${c.failed.join(', ')}`);
  finish(2);
}
out.push(`Baseline: ${CASES.length}/${CASES.length} cases pass (valid baseline).`, '');

const rows = MUTATORS.map((m) => {
  const res = runSuite(m.apply(BASELINE));
  const failedCases = res.filter((c) => c.failed.length);
  const killedBy = [...new Set(failedCases.flatMap((c) => c.failed))].sort();
  return { m, failedCases, r: { name: m.name, kind: m.kind, killed: failedCases.length > 0, killedBy } as MutantResult };
});
const s = summarize(rows.map((x) => x.r));
const violations = gate(s);

out.push(
  '## Summary', '',
  '| metric | value | CI threshold |', '|---|---|---|',
  `| Mutation score (killed / defect mutants) | **${s.killed}/${s.total} = ${pct(s.score)}** | >= ${pct(THRESHOLDS.minMutationScore)} |`,
  `| False alarm rate (killed benign / benign) | **${s.falseAlarms}/${s.benignTotal} = ${pct(s.falseAlarmRate)}** | <= ${pct(THRESHOLDS.maxFalseAlarmRate)} |`,
  `| Gate | ${violations.length ? 'FAIL: ' + violations.join('; ') : 'PASS'} | |`, '',
  '## Survivors (defects the suite did NOT detect -- coverage gaps)', '',
  ...(s.survivors.length ? s.survivors.map((n) => `- :warning: **GAP: \`${n}\`** -- no assertion failed on any case.`) : ['- none']), '',
  '## Defect mutants', '', '| mutant | family | result | failed cases | killed by assertions |', '|---|---|---|---|---|',
  ...rows.filter((x) => x.m.kind === 'defect').map(({ m, failedCases, r }) =>
    `| \`${m.name}\` | ${m.family} | ${r.killed ? 'killed' : '**SURVIVED**'} | ${failedCases.length}/${CASES.length} | ${r.killedBy.join(', ') || '-'} |`),
  '', '## Benign mutants (should survive)', '', '| mutant | result | failed cases | flagged by |', '|---|---|---|---|',
  ...rows.filter((x) => x.m.kind === 'benign').map(({ m, failedCases, r }) =>
    `| \`${m.name}\` | ${r.killed ? '**FALSE ALARM**' : 'ok (not flagged)'} | ${failedCases.length}/${CASES.length} ${failedCases.map((c) => c.id).join(' ')} | ${r.killedBy.join(', ') || '-'} |`),
);

// Per-assertion attribution: which assertion types kill which defect mutants, and which kills depend on a single assertion.
const defects = rows.filter((x) => x.m.kind === 'defect' && x.r.killed);
const names = [...new Set(defects.flatMap((x) => x.r.killedBy))].sort();
out.push('', '## Per-assertion kill attribution (defect mutants)', '', '| assertion | mutants killed | sole killer of |', '|---|---|---|');
for (const a of names) {
  const k = defects.filter((x) => x.r.killedBy.includes(a));
  const sole = k.filter((x) => x.r.killedBy.length === 1).map((x) => `\`${x.m.name}\``);
  out.push(`| \`${a}\` | ${k.length} | ${sole.join(', ') || '-'} |`);
}
finish(violations.length ? 1 : 0);
